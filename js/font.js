/** 3×5 version of a character; characters without one are sampled from the 5×7 glyph. */
export function smallGlyph(ch) {
  if (S[ch]) return S[ch];
  const big = glyph(ch);
  return [0, 2, 3, 4, 6].map((r) => ((big[r] >> 2) & 4) | ((big[r] >> 1) & 2) | (big[r] & 1));
}
